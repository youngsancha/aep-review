-- ═══════════════════════════ 옵션 A (권장): 복습상태 분리 ═══════════════════════════
-- srs_cards 는 '공용 카탈로그'(읽기 전용)로 남기고, 유저별 진도는 새 테이블 srs_progress 로.

create table if not exists srs_progress (
  id            bigint generated by default as identity primary key,
  user_id       uuid not null default auth.uid() references auth.users(id) on delete cascade,
  card_id       bigint not null references srs_cards(id) on delete cascade,
  ease          double precision default 2.5,
  interval_days integer default 0,
  due_date      date not null default current_date,
  reps          integer default 0,
  updated_at    timestamptz default now(),
  unique (user_id, card_id)
);
create index if not exists idx_srs_progress_user_due on srs_progress(user_id, due_date);

alter table srs_progress enable row level security;
drop policy if exists "own progress" on srs_progress;
create policy "own progress" on srs_progress
  for all to authenticated
  using (user_id = auth.uid())
  with check (user_id = auth.uid());
grant select, insert, update, delete on srs_progress to authenticated;

