-- 카탈로그 3종은 인증 유저에게 '읽기 전용'(쓰기는 ingest=service_role 만). 공개 publishable 키가
-- 노출돼도, 로그인 세션이 카탈로그를 변조하지 못하게 하는 심층방어.
drop policy if exists "authenticated all" on episodes;
drop policy if exists "authenticated all" on vocab_cards;
drop policy if exists "authenticated all" on srs_cards;
create policy "auth read" on episodes    for select to authenticated using (true);
create policy "auth read" on vocab_cards for select to authenticated using (true);
create policy "auth read" on srs_cards   for select to authenticated using (true);
revoke insert, update, delete on episodes, vocab_cards, srs_cards from authenticated;

